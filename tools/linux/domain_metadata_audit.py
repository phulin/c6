def got_symbol(module, address):
    """Resolve the target of an ELF64 GLOB_DAT symbol without loading the ELF."""
    raw = module.raw
    start = struct.unpack_from('<Q', raw, 40)[0]
    width, count = struct.unpack_from('<HH', raw, 58)
    sections = [struct.unpack_from('<IIQQQQIIQQ', raw, start + i * width)
                for i in range(count)]
    for section in sections:
        if section[1] != 4:
            continue
        for pos in range(section[4], section[4] + section[5], section[9]):
            target, info, addend = struct.unpack_from('<QQq', raw, pos)
            if target != address:
                continue
            if info & 0xffffffff != 6 or addend:
                raise ValueError('unexpected constructor GOT relocation')
            symbols = sections[section[6]]
            return struct.unpack_from('<Q', raw, symbols[4] + (info >> 32) * symbols[9] + 8)[0]
    raise ValueError('constructor GOT relocation missing')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--module', type=Path, default=ROOT.parent / 'c6-assets-linux/libGameCore_XP2.so')
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    module = Elf(args.module, GAME_SHA)
    source = (ROOT / 'native/linux/domain_metadata.c').read_text()
    bindings = [(field, int(address, 16)) for field, address in
                re.findall(r'BIND\(([^,]+),(0x[0-9a-f]+)\)', source)]
    expected = [(field, address) for field, address, _, _, _ in METHODS if field]
    if bindings != expected:
        raise ValueError('exporter BIND sequence differs from reviewed ABI packet')
    for _, address, size, name, digest in METHODS:
        if hashlib.sha256(module.read(address, size)).hexdigest() != digest:
            raise ValueError('original method fingerprint differs: ' + name)
