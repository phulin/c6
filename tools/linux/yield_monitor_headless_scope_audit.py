def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def component_bits(component):
    owner, kind, identity = component
    return (owner & 0xffff) | ((kind & 0xffff) << 16) | ((identity & 0xffffffff) << 32)


def route_key(route):
    return component_bits(route['origin']), component_bits(route['destination'])


def inspect_monitor(path):
    if sha(path) != MONITOR_SHA:
        raise ValueError('requires the attributed passive-4 native monitor preimage')
    monitor = json.loads(path.read_text())
    plots, trades = monitor['plots'], monitor['trades']
    active = monitor['native_trade']['active_routes_in_native_order']
    keys = [route_key(route) for route in trades]
    active_keys = [route_key(route) for route in active]
    if len(plots) != 6996 or len(trades) != 182 or len(active) != 182:
        raise ValueError('actual admitted fixture dimensions differ')
    if any(plot['size'] != 6 for plot in plots):
        raise ValueError('plot cache does not contain the actual six-yield domain')
    if any(left >= right for left, right in zip(keys, keys[1:])):
        raise ValueError('monitor keys must be strictly sorted and unique')
    if len(set(active_keys)) != len(active_keys) or set(keys) != set(active_keys):
        raise ValueError('actual active endpoints do not bijectively match cache keys')
    slots = [bisect_left(keys, key) for key in active_keys]
    if any(slot == len(keys) or keys[slot] != key for slot, key in zip(slots, active_keys)):
        raise ValueError('native lower_bound would not find an exact cache key')
    if len(set(slots)) != len(slots):
        raise ValueError('two active routes would update the same cache entry')
    if any(not route['path'] for route in active):
        raise ValueError('actual active route has an empty forward path')
    if len({route['edge_id'] for route in active}) != len(active):
        raise ValueError('active edge identities repeat')
    return dict(sha256=MONITOR_SHA, plots=len(plots), yields=6, active_routes=len(active),
                unique_exact_lower_bound_slots=len(set(slots)),
                active_path_nodes=sum(len(route['path']) for route in active),
                cache_keys_strictly_sorted=True, active_endpoints_unique=True,
                native_live_graph_lookup_hits_observed=False,
                computed_yield_values_replayed=False)


def executable_occurrences(image, value):
    header = struct.unpack_from('<Q', image.raw, 32)[0]
    width, count = struct.unpack_from('<HH', image.raw, 54)
    needle, hits = value.to_bytes(4, 'little'), []
    for index in range(count):
        kind, flags, offset, address, _, size, _, _ = struct.unpack_from(
            '<IIQQQQQQ', image.raw, header + index * width)
        if kind != 1 or not flags & 1:
            continue
        segment = image.raw[offset:offset + size]
        position = segment.find(needle)
        while position >= 0:
            hits.append(hex(address + position))
            position = segment.find(needle, position + 1)
    return hits


