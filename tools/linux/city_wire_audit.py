def normal(value):
    if isinstance(value,bytes):return list(value)
    if isinstance(value,(tuple,list)):return [normal(x) for x in value]
    if isinstance(value,dict):return {k:normal(v)for k,v in value.items()}
    return value

def leaves(value):
    if isinstance(value,dict):return sum(leaves(v)for v in value.values())
    if isinstance(value,list):return sum(leaves(v)for v in value)
    return 1

