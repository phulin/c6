#!/usr/bin/env python3
"""Recover guarded pure host configuration key initializers from exact target bytes."""
import hashlib
import json
from pathlib import Path
import struct
import sys
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT/'tools/analysis'))
from bootstrap_services_evidence import at_rva
HOST_SHA='e7450823cc8e00468cff7b9d7b97c63140eae38ae1d774ba4efa437556c42d63'
def recover():
    blob=(ROOT.parent/'c6-assets/Base/Binaries/Win64Steam/CivilizationVI.exe').read_bytes()
    if hashlib.sha256(blob).hexdigest()!=HOST_SHA: raise ValueError('unsupported host identity')
    rows=[]
    for pos in range(0x4000,0x7000):
        code=at_rva(blob,pos,27)
        if code[:7]!=bytes.fromhex('48 83 ec 28 48 8d 0d') or code[11]!=0xe8 or code[16:18]!=bytes.fromhex('89 05') or code[22:]!=bytes.fromhex('48 83 c4 28 c3'): continue
        call=pos+16+struct.unpack_from('<i',code,12)[0]
        target=pos+22+struct.unpack_from('<i',code,18)[0]
        literal=pos+11+struct.unpack_from('<i',code,7)[0]
        if call!=0x7a0da0 or not 0x22d6700<=target<0x22d7b90: continue
        key=at_rva(blob,literal,100).split(b'\0')[0].decode('ascii')
        rows.append(dict(initializer_rva=hex(pos),global_rva=hex(target),key=key,code_sha256=hashlib.sha256(code).hexdigest()))
    return rows
def main():
    rows=recover()
    header='/* Exact host pure CRC key initializers; generated by configuration_evidence.py. */\nstatic const uintptr_t configuration_key_initializers[] = {\n'
    header+=''.join(f'    {r["initializer_rva"]}, /* {r["key"]} */\n' for r in rows)+'};\n'
    (ROOT/'native/bootstrap/configuration/key_initializers.h').write_text(header)
    report=dict(host_sha256=HOST_SHA,crc_rva='0x7a0da0',pure_initializers=rows,player_key_array_initializer_rva='0x5a90',live_configuration_restored=False,gameplay_parity=False)
    destination=ROOT/'evidence/saves/configuration-key-initializers.json'
    destination.write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(dict(output=str(destination),pure_initializers=len(rows))))
if __name__=='__main__': main()
